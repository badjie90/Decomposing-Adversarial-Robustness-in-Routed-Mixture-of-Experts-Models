#!/usr/bin/env python3
"""Regenerate the manuscript tables from the audited aggregate CSV files.

Every selection asserts a unique record, five valid runs, and 5,000 valid paired
image bootstrap replicates. No reported estimate is typed manually. The primary
filter uses router-targeted attacks at 8/255, with N=2,000 for transfer-PGD and no
acquisition count for direct attacks. Run this script from any working directory.
"""
from __future__ import annotations

import csv
import argparse
import hashlib
import json
import math
from pathlib import Path


MANUSCRIPT = Path(__file__).resolve().parents[1]
SOURCE = MANUSCRIPT / "reference_results" / "tables"
OUTPUT = MANUSCRIPT / "results" / "paper" / "Tables"
DATASETS = ("bdd100k", "nuimages")
ATTACKS = ("hsj", "square", "transfer_pgd")
DATASET_NAMES = {"bdd100k": "BDD100K", "nuimages": "nuImages"}
ATTACK_NAMES = {"hsj": "HSJ", "square": "Square", "transfer_pgd": "Transfer-PGD"}
EPSILON = 8 / 255
ARCHITECTURES = {"csa": "csa_gmoe", "sparse": "custom_sparse_token_moe"}
PROVENANCE = []


def read_csv(name):
    with (SOURCE / name).open(newline="") as stream:
        return list(csv.DictReader(stream))


def one(rows, **criteria):
    def matches(row):
        for key, value in criteria.items():
            if key == "epsilon":
                if not math.isclose(float(row[key]), value, rel_tol=0, abs_tol=1e-12):
                    return False
            elif str(row[key]) != str(value):
                return False
        return True
    selected = [row for row in rows if matches(row)]
    if len(selected) != 1:
        raise ValueError(f"Expected one record for {criteria}, found {len(selected)}")
    row = selected[0]
    for field, expected in (("n_runs", 5), ("n_valid_runs", 5),
                            ("n_bootstrap", 5000), ("n_valid_bootstrap", 5000)):
        if int(row[field]) != expected:
            raise ValueError(f"Incomplete estimates for {criteria}: {field}={row[field]}")
    if not all(math.isfinite(float(row[field])) for field in ("mean", "ci_low", "ci_high", "run_sd")):
        raise ValueError(f"Non-finite estimate for {criteria}")
    PROVENANCE.append(criteria)
    return row


def metric(rows, dataset, attack, name, model="csa", acquisition=None):
    if acquisition is None:
        acquisition = 2000 if attack == "transfer_pgd" else ""
    return one(rows, dataset=dataset, model=model, architecture=ARCHITECTURES[model],
               attack=attack, target="router", epsilon=EPSILON,
               surrogate_acquisition_n=acquisition, metric=name)


def number(value, digits=3):
    # Avoid the scientifically unhelpful negative zero after rounding.
    rounded = round(float(value), digits)
    return f"{0.0 if rounded == 0 else rounded:.{digits}f}"


def estimate(row, digits=3, sign=1):
    mean = sign * float(row["mean"])
    lo, hi = sorted((sign * float(row["ci_low"]), sign * float(row["ci_high"])))
    return "$" + number(mean, digits) + r"\,[" + number(lo, digits) + r",\," + number(hi, digits) + "]$"


def scalar(row, field="mean", digits=3):
    return "$" + number(row[field], digits) + "$"


def line(cells):
    return " & ".join(cells) + r" \\" + "\n"


def table(name, caption, label, columns, header, body, *, size="small", tabsep="4pt"):
    content = (
        "% Generated by scripts/generate_tables.py from audited CSV results.\n"
        "\\begin{table*}[t]\n\\centering\n\\color{blue}\n"
        + "\\" + size + "\n\\setlength{\\tabcolsep}{" + tabsep + "}\n"
        + "\\caption{\\textcolor{blue}{" + caption + "}}\n"
        + "\\label{" + label + "}\n\\begin{tabular}{" + columns + "}\n"
        + "\\toprule\n" + header + "\\midrule\n" + body
        + "\\bottomrule\n\\end{tabular}\n\\end{table*}\n"
    )
    (OUTPUT / name).write_text(content)


def clean_metric(rows, dataset, name, model="csa"):
    records = [metric(rows, dataset, attack, "CC/" + name, model) for attack in ATTACKS]
    for key in ("mean", "ci_low", "ci_high"):
        if any(number(records[1][key]) != number(row[key]) for row in records):
            raise ValueError(f"Clean {name} differs between attacks for {dataset}/{model}")
    # Use Square clean inference as the common reference. Rank metrics can
    # differ below reported precision due to nearly tied floating-point scores.
    return records[1]


def primary(rows):
    body = ""
    for index, dataset in enumerate(DATASETS):
        if index:
            body += "\\addlinespace\n"
        body += line([DATASET_NAMES[dataset], "Clean", r"\multicolumn{1}{c}{--}",
                      r"\multicolumn{1}{c}{--}", estimate(clean_metric(rows, dataset, "macro_f1")),
                      scalar(clean_metric(rows, dataset, "map")), scalar(clean_metric(rows, dataset, "macro_auroc"))])
        for attack in ATTACKS:
            body += line(["", ATTACK_NAMES[attack],
                          estimate(metric(rows, dataset, attack, "routing/router_asr")),
                          scalar(metric(rows, dataset, attack, "routing/routing_l1_shift")),
                          estimate(metric(rows, dataset, attack, "AA/macro_f1")),
                          scalar(metric(rows, dataset, attack, "AA/map")),
                          scalar(metric(rows, dataset, attack, "AA/macro_auroc"))])
    table("primary.tex",
          r"CSA-GMoE prediction and routing outcomes at $\varepsilon=8/255$. Direct attacks use 1,000 target queries. Transfer-PGD uses $N=2{,}000$ acquisition images. Entries report five-run means. Brackets give 95\% paired image bootstrap intervals conditional on the fitted models and observed seeds. Clean rows give the unperturbed baseline. Route ASR is the clean-reference top-1 flip rate. Prediction metrics use AA for attacked inputs.",
          "tab:primary_csa_results", "llccccc",
          line([r"\textbf{Dataset}", r"\textbf{Attack}", r"\textbf{Route ASR}",
                r"\shortstack{\textbf{Routing}\\$L_1$ \textbf{shift}}",
                r"\textbf{Macro F1}", r"\textbf{mAP}", r"\shortstack{\textbf{Macro}\\\textbf{AUROC}}"]), body)


def attribution(rows):
    body = ""
    for index, dataset in enumerate(DATASETS):
        if index:
            body += "\\addlinespace\n"
        for j, attack in enumerate(ATTACKS):
            values = [estimate(metric(rows, dataset, attack, "attribution/" + key + "/macro_f1"), 4)
                      for key in ("delta_full", "delta_feature_only", "delta_route_only", "routing_recovery")]
            body += line([DATASET_NAMES[dataset] if j == 0 else "", ATTACK_NAMES[attack], *values])
    table("attribution.tex",
          r"Controlled macro-F1 contrasts for CSA-GMoE at $\varepsilon=8/255$. Entries are five-run means with 95\% paired image bootstrap intervals conditional on fitted models and observed seeds. $\Delta_{\mathrm{full}}=M_{\mathrm{CC}}-M_{\mathrm{AA}}$, $\Delta_{\mathrm{feature}}=M_{\mathrm{CC}}-M_{\mathrm{AC}}$, $\Delta_{\mathrm{route}}=M_{\mathrm{CC}}-M_{\mathrm{CA}}$, and $R=M_{\mathrm{AC}}-M_{\mathrm{AA}}$. The feature contrast combines shared-representation and expert corruption. $R$ measures clean-routing restoration on corrupted expert features.",
          "tab:controlled_attribution", "llcccc",
          line([r"\textbf{Dataset}", r"\textbf{Attack}", r"$\Delta_{\mathrm{full}}$",
                r"$\Delta_{\mathrm{feature}}$", r"$\Delta_{\mathrm{route}}$", r"$R$"]),
          body, size="footnotesize", tabsep="3pt")


def controls(rows):
    body = ""
    for index, dataset in enumerate(DATASETS):
        if index:
            body += "\\addlinespace\n"
        for j, attack in enumerate(ATTACKS):
            cells = [DATASET_NAMES[dataset] if j == 0 else "", ATTACK_NAMES[attack]]
            for name, sign in (("router_flip_rate_excess", 1), ("routing_l1_shift_excess", 1),
                               ("macro_f1_degradation_excess", -1)):
                row = one(rows, dataset=dataset, model="csa", architecture="csa_gmoe", attack=attack,
                          epsilon=EPSILON, surrogate_acquisition_n=2000 if attack == "transfer_pgd" else "", contrast=name)
                cells.append(estimate(row, sign=sign))
            body += line(cells)
    table("controls.tex",
          r"Matched attack-target contrasts for CSA-GMoE at $\varepsilon=8/255$. Every column reports router-targeted minus fused-output-targeted outcomes on the same images and seeds. Positive routing contrasts indicate greater routing disruption under the router objective. Positive F1 differences indicate lower F1 under the fused-output objective. Brackets give 95\% paired image bootstrap intervals conditional on fitted models and observed seeds.",
          "tab:matched_target_controls", "llccc",
          line([r"\textbf{Dataset}", r"\textbf{Attack}", r"\textbf{Route-flip difference}",
                r"\textbf{$L_1$-shift difference}", r"\textbf{Macro-F1 difference}"]), body)


def sparse(rows):
    body = ""
    for index, dataset in enumerate(DATASETS):
        if index:
            body += "\\addlinespace\n"
        body += line([DATASET_NAMES[dataset], "Clean", "--",
                      estimate(clean_metric(rows, dataset, "macro_f1", "sparse")), "--"])
        for attack in ATTACKS:
            body += line(["", ATTACK_NAMES[attack],
                          estimate(metric(rows, dataset, attack, "routing/router_asr", "sparse")),
                          estimate(metric(rows, dataset, attack, "AA/macro_f1", "sparse")),
                          estimate(metric(rows, dataset, attack, "attribution/routing_recovery/macro_f1", "sparse"), 4)])
    table("sparse.tex",
          r"Custom sparse token-MoE results at $\varepsilon=8/255$. Route ASR refers to the dominant expert in the image-averaged token routing weights. Recovery $R=M_{\mathrm{AC}}-M_{\mathrm{AA}}$ uses full token routing maps. Entries are five-run means with 95\% paired image bootstrap intervals conditional on fitted models and observed seeds. Clean rows provide the unperturbed macro-F1 baseline. This structural comparison does not hold model capacity or training procedure fixed.",
          "tab:sparse_control", "llccc",
          line([r"\textbf{Dataset}", r"\textbf{Attack}", r"\textbf{Route ASR}",
                r"\textbf{Macro F1}", r"\textbf{Recovery $R$}"]), body)


def transfer(rows):
    body = ""
    for n in (50, 100, 250, 500, 1000, 2000):
        cells = [str(n)]
        for dataset in DATASETS:
            cells.extend(scalar(metric(rows, dataset, "transfer_pgd", name, acquisition=n))
                         for name in ("routing/surrogate_clean_routing_agreement", "routing/router_asr", "AA/macro_f1"))
        body += line(cells)
    header = (line(["", r"\multicolumn{3}{c}{\textbf{BDD100K}}", r"\multicolumn{3}{c}{\textbf{nuImages}}"])
              + r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}" + "\n"
              + line([r"\textbf{$N$}", r"\textbf{Agreement}", r"\textbf{Target flip}", r"\textbf{AA F1}",
                      r"\textbf{Agreement}", r"\textbf{Target flip}", r"\textbf{AA F1}"]))
    table("transfer.tex",
          r"CSA-GMoE router-surrogate acquisition scaling at $\varepsilon=8/255$. Values are means over five independently initialized surrogate runs. Agreement compares surrogate and target clean routes on the evaluation cohort. Target flip and AA F1 evaluate the target model. Each surrogate uses $N$ clean target responses from a shared bank acquired with 2,000 image queries. Perturbation generation uses no additional target queries.",
          "tab:transfer_scaling", "rcccccc", header, body)


def uncertainty(rows):
    body = ""
    for index, dataset in enumerate(DATASETS):
        if index:
            body += "\\addlinespace\n"
        for j, attack in enumerate(ATTACKS):
            f1 = metric(rows, dataset, attack, "AA/macro_f1")
            body += line([DATASET_NAMES[dataset] if j == 0 else "", ATTACK_NAMES[attack],
                          scalar(f1), scalar(f1, "run_sd", digits=4),
                          estimate(metric(rows, dataset, attack, "AA/map")),
                          estimate(metric(rows, dataset, attack, "AA/macro_auroc"))])
    table("uncertainty.tex",
          r"Additional uncertainty estimates for primary CSA-GMoE router-targeted outcomes at $\varepsilon=8/255$. SD is the sample standard deviation of macro F1 across five attack or surrogate runs. Brackets give 95\% paired image bootstrap intervals for mAP and macro AUROC. These intervals condition on fitted models and the observed seeds and do not estimate variability across target-model training runs.",
          "tab:primary_uncertainty", "llcccc",
          line([r"\textbf{Dataset}", r"\textbf{Attack}", r"\textbf{Macro F1}",
                r"\textbf{F1 SD}", r"\textbf{mAP}", r"\textbf{Macro AUROC}"]), body)


def main():
    global SOURCE, OUTPUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables-dir", type=Path, default=SOURCE)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT)
    args = parser.parse_args()
    SOURCE, OUTPUT = args.tables_dir.resolve(), args.output_dir.resolve()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    summary = read_csv("metrics_summary.csv")
    contrasts = read_csv("matched_target_contrasts.csv")
    primary(summary)
    attribution(summary)
    controls(contrasts)
    sparse(summary)
    transfer(summary)
    uncertainty(summary)
    hashes = {name: hashlib.sha256((SOURCE / name).read_bytes()).hexdigest()
              for name in ("metrics_summary.csv", "matched_target_contrasts.csv")}
    (OUTPUT / "provenance.json").write_text(json.dumps({"source_sha256": hashes,
        "epsilon": EPSILON, "selected_records": PROVENANCE}, indent=2) + "\n")
    print(f"Generated six tables and provenance in {OUTPUT}")


if __name__ == "__main__":
    main()
